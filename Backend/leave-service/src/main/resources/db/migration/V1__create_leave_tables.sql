-- ============================================================
-- File: V1__create_leave_tables.sql
-- Project: Nexa
-- Service: leave-service
-- Database: PostgreSQL 16+
-- Description: 휴가 관리 서비스 초기 테이블 및 인덱스 생성
--
-- MSA 설계 원칙
-- 1. HR Service의 employee 테이블은 생성하지 않음
-- 2. Approval Service의 결재 테이블은 생성하지 않음
-- 3. 외부 서비스의 ID는 BIGINT 값으로만 저장
-- 4. Leave Service 내부 테이블에만 FK 적용
-- 5. 휴가 발생, 사용, 복원은 원장 기반으로 관리
--
-- 시간 컬럼 규칙
-- 1. 날짜/시각 컬럼은 모두 TIMESTAMPTZ 사용
-- 2. 날짜 의미의 값은 Asia/Seoul 자정 시각으로 저장
-- 3. 기간은 반개구간 [시작, 종료) : 시작 포함, 종료 미포함
-- ============================================================


-- ============================================================
-- 1. 휴가 정책 그룹
-- ============================================================

CREATE TABLE leave_policy_group (
                                    policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    name      VARCHAR(100) NOT NULL
);

COMMENT ON TABLE leave_policy_group IS '휴가 정책 그룹';


-- ============================================================
-- 2. 휴가 정책 버전
-- ============================================================

CREATE TABLE leave_policy_version (
                                      policy_version_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      policy_id                BIGINT       NOT NULL,
                                      version_no               INT          NOT NULL,
                                      effective_from           TIMESTAMPTZ  NOT NULL,
                                      effective_to             TIMESTAMPTZ,
                                      base_type                VARCHAR(20)  NOT NULL,
                                      fiscal_start             VARCHAR(5),
                                      unit_minutes             INT          NOT NULL DEFAULT 30,
                                      carry_over_allowed       BOOLEAN      NOT NULL DEFAULT FALSE,
                                      carry_over_limit_minutes INT,
                                      expiry_rule              VARCHAR(50)  NOT NULL DEFAULT 'END_OF_VALIDITY',
                                      created_at               TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                      CONSTRAINT fk_policy_version_group
                                          FOREIGN KEY (policy_id)
                                              REFERENCES leave_policy_group (policy_id),

                                      CONSTRAINT uq_policy_version
                                          UNIQUE (policy_id, version_no),

                                      CONSTRAINT ck_policy_base_type
                                          CHECK (base_type IN ('HIRE_DATE', 'FISCAL_YEAR')),

                                      CONSTRAINT ck_policy_period
                                          CHECK (effective_to IS NULL OR effective_to > effective_from),

                                      CONSTRAINT ck_policy_unit
                                          CHECK (unit_minutes > 0),

                                      CONSTRAINT ck_policy_carry_limit
                                          CHECK (carry_over_limit_minutes IS NULL OR carry_over_limit_minutes >= 0)
);

COMMENT ON TABLE  leave_policy_version                IS '휴가 정책 버전 및 시행 기간';
COMMENT ON COLUMN leave_policy_version.effective_from IS '시행 시작 시각 (포함)';
COMMENT ON COLUMN leave_policy_version.effective_to   IS '시행 종료 시각 (미포함, NULL이면 무기한)';
COMMENT ON COLUMN leave_policy_version.fiscal_start   IS '회계연도 시작 월-일 (MM-DD)';


-- ============================================================
-- 3. 휴가 잔액 유형
-- ============================================================

CREATE TABLE leave_balance_type (
                                    balance_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    name            VARCHAR(100) NOT NULL UNIQUE,
                                    is_active       BOOLEAN      NOT NULL DEFAULT TRUE
);

COMMENT ON TABLE leave_balance_type IS '연차, 보상휴가 등 잔액 유형';


-- ============================================================
-- 4. 휴가 유형
-- ============================================================

CREATE TABLE leave_type (
                            leave_type_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            balance_type_id BIGINT,
                            name            VARCHAR(100) NOT NULL,
                            is_paid         BOOLEAN      NOT NULL DEFAULT TRUE,
                            balance_mode    VARCHAR(20)  NOT NULL DEFAULT 'ACCOUNT',
                            request_unit    VARCHAR(20)  NOT NULL DEFAULT 'DAY',
                            max_minutes     INT,

                            CONSTRAINT fk_leave_type_balance
                                FOREIGN KEY (balance_type_id)
                                    REFERENCES leave_balance_type (balance_type_id),

                            CONSTRAINT ck_leave_type_balance_mode
                                CHECK (balance_mode IN ('ACCOUNT', 'NONE')),

                            CONSTRAINT ck_leave_type_request_unit
                                CHECK (request_unit IN ('DAY', 'HALF_DAY', 'HOUR', 'MIXED')),

                            CONSTRAINT ck_leave_type_max_minutes
                                CHECK (max_minutes IS NULL OR max_minutes > 0),

                            CONSTRAINT ck_leave_type_account
                                CHECK (balance_mode <> 'ACCOUNT' OR balance_type_id IS NOT NULL)
);

COMMENT ON TABLE leave_type IS '연차, 반차, 병가 등 휴가 유형';


-- ============================================================
-- 5. 연차 자동 발생 규칙
-- ============================================================

CREATE TABLE leave_accrual_rule (
                                    rule_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    policy_version_id  BIGINT      NOT NULL,
                                    min_service_months INT         NOT NULL DEFAULT 0,
                                    max_service_months INT,
                                    frequency          VARCHAR(20) NOT NULL,
                                    grant_minutes      INT         NOT NULL,
                                    is_active          BOOLEAN     NOT NULL DEFAULT TRUE,

                                    CONSTRAINT fk_accrual_policy
                                        FOREIGN KEY (policy_version_id)
                                            REFERENCES leave_policy_version (policy_version_id),

                                    CONSTRAINT ck_accrual_frequency
                                        CHECK (frequency IN ('MONTHLY', 'YEARLY', 'ON_HIRE', 'CUSTOM')),

                                    CONSTRAINT ck_accrual_months
                                        CHECK (
                                            min_service_months >= 0
                                                AND (max_service_months IS NULL OR max_service_months >= min_service_months)
                                            ),

                                    CONSTRAINT ck_accrual_grant_minutes
                                        CHECK (grant_minutes > 0)
);

COMMENT ON TABLE leave_accrual_rule IS '근속 기간에 따른 연차 자동 발생 규칙';


-- ============================================================
-- 6. 정책별 휴가 유형 신청 규칙
-- ============================================================

CREATE TABLE leave_policy_type_rule (
                                        rule_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        policy_version_id BIGINT      NOT NULL,
                                        leave_type_id     BIGINT      NOT NULL,
                                        is_requestable    BOOLEAN     NOT NULL DEFAULT TRUE,
                                        allowed_units     VARCHAR(30) NOT NULL DEFAULT 'FULL',
                                        min_minutes       INT,
                                        max_minutes       INT,

                                        CONSTRAINT fk_policy_type_version
                                            FOREIGN KEY (policy_version_id)
                                                REFERENCES leave_policy_version (policy_version_id),

                                        CONSTRAINT fk_policy_type_leave
                                            FOREIGN KEY (leave_type_id)
                                                REFERENCES leave_type (leave_type_id),

                                        CONSTRAINT uq_policy_type
                                            UNIQUE (policy_version_id, leave_type_id),

                                        CONSTRAINT ck_policy_type_units
                                            CHECK (allowed_units IN ('FULL', 'HALF', 'HOUR', 'MIXED')),

                                        CONSTRAINT ck_policy_type_minutes
                                            CHECK (
                                                (min_minutes IS NULL OR min_minutes > 0)
                                                    AND (max_minutes IS NULL OR max_minutes > 0)
                                                    AND (min_minutes IS NULL OR max_minutes IS NULL OR min_minutes <= max_minutes)
                                                )
);

COMMENT ON TABLE leave_policy_type_rule IS '정책 버전별 휴가 유형 신청 허용 규칙';


-- ============================================================
-- 7. 직원별 휴가 정책 배정
--
-- emp_id: HR Service의 employee.emp_id
-- 외부 서비스이므로 FK 생성하지 않음
-- ============================================================

CREATE TABLE employee_leave_policy_assignment (
                                                  assignment_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                  emp_id         BIGINT      NOT NULL,
                                                  policy_id      BIGINT      NOT NULL,
                                                  effective_from TIMESTAMPTZ NOT NULL,
                                                  effective_to   TIMESTAMPTZ,

                                                  CONSTRAINT fk_assignment_policy
                                                      FOREIGN KEY (policy_id)
                                                          REFERENCES leave_policy_group (policy_id),

                                                  CONSTRAINT uq_employee_policy_start
                                                      UNIQUE (emp_id, effective_from),

                                                  CONSTRAINT ck_assignment_period
                                                      CHECK (effective_to IS NULL OR effective_to > effective_from)
);

COMMENT ON TABLE  employee_leave_policy_assignment                IS '직원별 휴가 정책 적용 이력';
COMMENT ON COLUMN employee_leave_policy_assignment.emp_id         IS 'HR Service 직원 ID, 외부 논리 참조';
COMMENT ON COLUMN employee_leave_policy_assignment.effective_from IS '적용 시작 시각 (포함)';
COMMENT ON COLUMN employee_leave_policy_assignment.effective_to   IS '적용 종료 시각 (미포함, NULL이면 무기한)';


-- ============================================================
-- 8. 직원별 휴가 계정
--
-- emp_id: HR Service에서 관리
-- ============================================================

CREATE TABLE leave_account (
                               account_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               emp_id          BIGINT NOT NULL,
                               balance_type_id BIGINT NOT NULL,

                               CONSTRAINT fk_account_balance_type
                                   FOREIGN KEY (balance_type_id)
                                       REFERENCES leave_balance_type (balance_type_id),

                               CONSTRAINT uq_leave_account_employee_type
                                   UNIQUE (emp_id, balance_type_id)
);

COMMENT ON TABLE  leave_account        IS '직원별 휴가 잔액 계정';
COMMENT ON COLUMN leave_account.emp_id IS 'HR Service 직원 ID, 외부 논리 참조';


-- ============================================================
-- 9. 휴가 발생분
-- ============================================================

CREATE TABLE leave_grant (
                             grant_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             account_id        BIGINT      NOT NULL,
                             policy_version_id BIGINT,
                             rule_id           BIGINT,
                             parent_grant_id   BIGINT,
                             grant_kind        VARCHAR(20) NOT NULL,
                             granted_on        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             original_minutes  INT         NOT NULL,
                             valid_from        TIMESTAMPTZ NOT NULL,
                             expires_on        TIMESTAMPTZ,
                             created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                             CONSTRAINT fk_grant_account
                                 FOREIGN KEY (account_id)
                                     REFERENCES leave_account (account_id),

                             CONSTRAINT fk_grant_policy
                                 FOREIGN KEY (policy_version_id)
                                     REFERENCES leave_policy_version (policy_version_id),

                             CONSTRAINT fk_grant_accrual_rule
                                 FOREIGN KEY (rule_id)
                                     REFERENCES leave_accrual_rule (rule_id),

                             CONSTRAINT fk_grant_parent
                                 FOREIGN KEY (parent_grant_id)
                                     REFERENCES leave_grant (grant_id),

                             CONSTRAINT ck_grant_kind
                                 CHECK (grant_kind IN ('AUTO', 'MANUAL', 'CARRY_OVER', 'COMP')),

                             CONSTRAINT ck_grant_minutes
                                 CHECK (original_minutes > 0),

                             CONSTRAINT ck_grant_period
                                 CHECK (expires_on IS NULL OR expires_on > valid_from),

                             CONSTRAINT uq_grant_account_pair
                                 UNIQUE (grant_id, account_id)
);

COMMENT ON TABLE  leave_grant            IS '자동 발생, 수동 지급, 이월 등 휴가 발생분';
COMMENT ON COLUMN leave_grant.valid_from IS '사용 가능 시작 시각 (포함)';
COMMENT ON COLUMN leave_grant.expires_on IS '소멸 시각 (미포함, NULL이면 무기한)';


-- ============================================================
-- 10. 휴가 신청
--
-- emp_id: HR Service의 직원 ID
-- cancelled_by: HR Service의 직원 ID
-- approval_doc_id: Approval Service 결재 문서 ID
-- ============================================================

CREATE TABLE leave_request (
                               leave_req_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               policy_version_id    BIGINT        NOT NULL,
                               leave_type_id        BIGINT        NOT NULL,
                               emp_id               BIGINT        NOT NULL,
                               approval_doc_id      BIGINT,
                               total_minutes        INT           NOT NULL DEFAULT 0,
                               total_deduct_minutes INT           NOT NULL DEFAULT 0,
                               reason               VARCHAR(2000),
                               status               VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',
                               submitted_at         TIMESTAMPTZ,
                               cancelled_at         TIMESTAMPTZ,
                               cancelled_by         BIGINT,
                               cancel_reason        VARCHAR(2000),
                               created_at           TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
                               updated_at           TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               CONSTRAINT fk_request_policy
                                   FOREIGN KEY (policy_version_id)
                                       REFERENCES leave_policy_version (policy_version_id),

                               CONSTRAINT fk_request_leave_type
                                   FOREIGN KEY (leave_type_id)
                                       REFERENCES leave_type (leave_type_id),

                               CONSTRAINT uq_request_approval_doc
                                   UNIQUE (approval_doc_id),

                               CONSTRAINT ck_request_status
                                   CHECK (status IN (
                                                     'DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED', 'WITHDRAWN', 'CANCELLED'
                                       )),

                               CONSTRAINT ck_request_minutes
                                   CHECK (total_minutes >= 0 AND total_deduct_minutes >= 0)
);

COMMENT ON TABLE  leave_request                 IS '휴가 신청 및 결재 상태';
COMMENT ON COLUMN leave_request.emp_id          IS 'HR Service 직원 ID';
COMMENT ON COLUMN leave_request.approval_doc_id IS 'Approval Service 결재 문서 ID';
COMMENT ON COLUMN leave_request.cancelled_by    IS '휴가 취소 처리 직원 ID';


-- ============================================================
-- 11. 휴가 신청 날짜 상세
-- ============================================================

CREATE TABLE leave_request_date (
                                    request_date_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    leave_req_id           BIGINT      NOT NULL,
                                    leave_date             TIMESTAMPTZ NOT NULL,
                                    portion                VARCHAR(20) NOT NULL,
                                    start_at               TIMESTAMPTZ,
                                    end_at                 TIMESTAMPTZ,
                                    scheduled_work_minutes INT,
                                    requested_minutes      INT         NOT NULL,
                                    deduct_minutes         INT         NOT NULL,

                                    CONSTRAINT fk_request_date_request
                                        FOREIGN KEY (leave_req_id)
                                            REFERENCES leave_request (leave_req_id),

                                    CONSTRAINT ck_request_date_portion
                                        CHECK (portion IN ('FULL', 'AM_HALF', 'PM_HALF', 'HOURLY')),

                                    CONSTRAINT ck_request_date_time
                                        CHECK (end_at IS NULL OR start_at IS NULL OR end_at > start_at),

                                    CONSTRAINT ck_request_date_minutes
                                        CHECK (
                                            requested_minutes > 0
                                                AND deduct_minutes >= 0
                                                AND (scheduled_work_minutes IS NULL OR scheduled_work_minutes >= 0)
                                            )
);

COMMENT ON TABLE  leave_request_date            IS '휴가 신청의 날짜별 상세 내역';
COMMENT ON COLUMN leave_request_date.leave_date IS '휴가 일자 (Asia/Seoul 자정 시각)';


-- ============================================================
-- 12. 휴가 원장
--
-- 휴가 발생 / 예약 / 사용 / 복원 / 소멸 이력 관리
-- 기존 내역 수정 대신 새로운 원장 내역 추가
-- ============================================================

CREATE TABLE leave_ledger (
                              entry_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              account_id        BIGINT       NOT NULL,
                              reverses_entry_id BIGINT,
                              grant_id          BIGINT       NOT NULL,
                              leave_req_id      BIGINT,
                              event_type        VARCHAR(20)  NOT NULL,
                              quantity_delta    INT          NOT NULL DEFAULT 0,
                              reserved_delta    INT          NOT NULL DEFAULT 0,
                              reason            VARCHAR(500),
                              created_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              idempotency_key   VARCHAR(120) NOT NULL,

                              CONSTRAINT fk_ledger_account
                                  FOREIGN KEY (account_id)
                                      REFERENCES leave_account (account_id),

                              CONSTRAINT fk_ledger_grant_account
                                  FOREIGN KEY (grant_id, account_id)
                                      REFERENCES leave_grant (grant_id, account_id),

                              CONSTRAINT fk_ledger_request
                                  FOREIGN KEY (leave_req_id)
                                      REFERENCES leave_request (leave_req_id),

                              CONSTRAINT fk_ledger_reverse
                                  FOREIGN KEY (reverses_entry_id)
                                      REFERENCES leave_ledger (entry_id),

                              CONSTRAINT uq_ledger_idempotency
                                  UNIQUE (idempotency_key),

                              CONSTRAINT uq_ledger_reversal
                                  UNIQUE (reverses_entry_id),

                              CONSTRAINT ck_ledger_event
                                  CHECK (event_type IN (
                                                        'GRANT', 'ADJUST', 'RESERVE', 'RELEASE', 'CONSUME',
                                                        'RESTORE', 'EXPIRE', 'REVOKE', 'CARRY_OUT', 'CARRY_IN'
                                      )),

                              CONSTRAINT ck_ledger_delta
                                  CHECK (quantity_delta <> 0 OR reserved_delta <> 0)
);

COMMENT ON TABLE leave_ledger IS '휴가 발생, 예약, 차감, 복원 및 소멸 원장';


-- ============================================================
-- INDEX
--
-- 직원별 정책 적용 이력: uq_employee_policy_start (emp_id, effective_from) 인덱스로 대체
-- 직원별 휴가 계정:     uq_leave_account_employee_type (emp_id, balance_type_id) 인덱스로 대체
-- ============================================================

-- 정책 버전 시행 기간
CREATE INDEX idx_policy_version_effective
    ON leave_policy_version (policy_id, effective_from, effective_to);

-- 직원별 휴가 신청 목록
CREATE INDEX idx_leave_request_emp_status
    ON leave_request (emp_id, status, created_at DESC);

-- 휴가 신청 날짜 상세
CREATE INDEX idx_leave_request_date
    ON leave_request_date (leave_req_id, leave_date);

-- 휴가 발생분 유효기간 조회
CREATE INDEX idx_leave_grant_account_expiry
    ON leave_grant (account_id, expires_on);

-- 계정별 휴가 원장 조회
CREATE INDEX idx_leave_ledger_account_time
    ON leave_ledger (account_id, created_at DESC);

-- 휴가 신청별 차감/복원 이력 조회
CREATE INDEX idx_leave_ledger_request
    ON leave_ledger (leave_req_id);

-- 발생분별 휴가 원장 조회
CREATE INDEX idx_leave_ledger_grant
    ON leave_ledger (grant_id);

