-- 레거시 신청은 새 추적 정보 없이 보존한다. SUBMITTING부터 신규 계약을 강제한다.
ALTER TABLE leave_request DROP CONSTRAINT ck_request_status;
ALTER TABLE leave_request
    ADD COLUMN submission_key VARCHAR(128),
    ADD COLUMN submission_payload_hash VARCHAR(64),
    ADD COLUMN approval_creation_status VARCHAR(20),
    ADD COLUMN approval_request_id UUID,
    ADD COLUMN approval_status_changed_at TIMESTAMPTZ,
    ADD COLUMN approval_last_error VARCHAR(500),
    ADD COLUMN approval_attempt_count INT,
    ADD CONSTRAINT ck_request_status CHECK (status IN
        ('DRAFT','SUBMITTING','SUBMITTED','APPROVED','REJECTED','WITHDRAWN','CANCELLED')),
    ADD CONSTRAINT uq_request_submission UNIQUE (emp_id, submission_key),
    ADD CONSTRAINT uq_request_approval_request UNIQUE (approval_request_id),
    ADD CONSTRAINT uq_request_employee_pair UNIQUE (leave_req_id, emp_id),
    ADD CONSTRAINT ck_request_submission_metadata CHECK (
        CASE WHEN submission_key IS NULL THEN
            submission_payload_hash IS NULL AND approval_creation_status IS NULL
            AND approval_request_id IS NULL AND approval_status_changed_at IS NULL
            AND approval_last_error IS NULL AND approval_attempt_count IS NULL
        ELSE
            submission_key !~ '^[[:space:]]*$'
            AND submission_payload_hash IS NOT NULL
            AND submission_payload_hash ~ '^[0-9a-f]{64}$'
            AND approval_creation_status IS NOT NULL
            AND approval_creation_status IN ('NOT_SENT','IN_PROGRESS','UNKNOWN','LINKED','FAILED')
            AND approval_request_id IS NOT NULL AND approval_status_changed_at IS NOT NULL
            AND approval_attempt_count IS NOT NULL AND approval_attempt_count >= 0
            AND ((approval_creation_status = 'LINKED' AND approval_doc_id IS NOT NULL)
                 OR (approval_creation_status <> 'LINKED' AND approval_doc_id IS NULL))
            AND (status NOT IN ('SUBMITTED','APPROVED','REJECTED') OR approval_creation_status = 'LINKED')
            AND (approval_creation_status <> 'FAILED' OR status = 'CANCELLED')
            AND (approval_creation_status <> 'LINKED' OR status IN
                 ('SUBMITTED','APPROVED','REJECTED','WITHDRAWN','CANCELLED'))
            AND (approval_creation_status NOT IN ('NOT_SENT','IN_PROGRESS','UNKNOWN')
                 OR status IN ('DRAFT','SUBMITTING'))
            AND (status <> 'DRAFT' OR approval_creation_status = 'NOT_SENT')
        END
    ),
    ADD CONSTRAINT ck_request_submitting CHECK (
        status <> 'SUBMITTING' OR
        (submission_key IS NOT NULL AND approval_doc_id IS NULL
         AND approval_creation_status IN ('NOT_SENT','IN_PROGRESS','UNKNOWN'))
    );

-- 기존 PK에 보조 UNIQUE만 추가하며 행과 컬럼은 변경하지 않는다.
ALTER TABLE leave_request_date ADD CONSTRAINT uq_request_date_pair UNIQUE (leave_req_id, request_date_id);
ALTER TABLE leave_account ADD CONSTRAINT uq_account_employee_pair UNIQUE (account_id, emp_id);

CREATE TABLE leave_request_allocation (
    allocation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leave_req_id BIGINT NOT NULL,
    request_date_id BIGINT NOT NULL,
    emp_id BIGINT NOT NULL,
    account_id BIGINT NOT NULL,
    grant_id BIGINT NOT NULL,
    allocated_minutes INT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_allocation_minutes CHECK (allocated_minutes > 0),
    CONSTRAINT uq_allocation_date_grant UNIQUE (request_date_id, grant_id),
    CONSTRAINT uq_allocation_ledger_pair UNIQUE (allocation_id, leave_req_id, account_id, grant_id),
    CONSTRAINT fk_allocation_request_date FOREIGN KEY (leave_req_id, request_date_id)
        REFERENCES leave_request_date (leave_req_id, request_date_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_allocation_request_employee FOREIGN KEY (leave_req_id, emp_id)
        REFERENCES leave_request (leave_req_id, emp_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_allocation_account_employee FOREIGN KEY (account_id, emp_id)
        REFERENCES leave_account (account_id, emp_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_allocation_grant_account FOREIGN KEY (grant_id, account_id)
        REFERENCES leave_grant (grant_id, account_id) ON UPDATE RESTRICT ON DELETE RESTRICT
);

ALTER TABLE leave_ledger
    ADD COLUMN allocation_id BIGINT,
    ADD CONSTRAINT ck_ledger_allocation_request CHECK (allocation_id IS NULL OR leave_req_id IS NOT NULL),
    ADD CONSTRAINT fk_ledger_allocation FOREIGN KEY (allocation_id, leave_req_id, account_id, grant_id)
        REFERENCES leave_request_allocation (allocation_id, leave_req_id, account_id, grant_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT;

CREATE INDEX idx_allocation_request ON leave_request_allocation (leave_req_id);
CREATE INDEX idx_allocation_account_employee ON leave_request_allocation (account_id, emp_id);
CREATE INDEX idx_allocation_grant_account ON leave_request_allocation (grant_id, account_id);
CREATE INDEX idx_ledger_allocation ON leave_ledger (allocation_id) WHERE allocation_id IS NOT NULL;
CREATE INDEX idx_request_pending_approval ON leave_request (approval_status_changed_at, leave_req_id)
    WHERE status = 'SUBMITTING';
